export const dict = {
  kh: Object.fromEntries(Object.entries(S).map(([k, v]) => [k, v[0]])),
  en: Object.fromEntries(Object.entries(S).map(([k, v]) => [k, v[1]])),
};

export function translate(lang, key, vars) {
  let out = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  return out;
}

export const localize = (value, lang) => {
  if (value == null) return '';
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  return value[lang] || value.en || value.kh || '';
};
