#!/usr/bin/env node
/**
 * Interactive, security-conscious setup for REAL payment → REAL diamonds.
 *
 * It does NOT invent or download credentials. It asks for the values issued to
 * YOUR verified Bakong account and YOUR funded Shop2Topup reseller account,
 * generates strong local secrets, and writes a git-ignored .env (mode 0600).
 */
import 'dotenv/config';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import {
  isPostgresUrl, isHttpsUrl, isRealValue, isBakongAccountId,
  isShop2TopupKey, isStrongSecret,
} from '../server/credentials.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_PATH = path.join(ROOT, '.env');
const e = process.env;

const IS_TTY = Boolean(process.stdin.isTTY);
const rl = IS_TTY ? readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true }) : null;
let pipedLines = [];
if (!IS_TTY) {
  try { pipedLines = fs.readFileSync(0, 'utf8').split(/\r?\n/); }
  catch { pipedLines = []; }
}
let lineIndex = 0;

function ask(query, { hidden = false, defaultValue = '' } = {}) {
  if (IS_TTY) {
    return new Promise((resolve) => {
      const original = rl._writeToOutput;
      if (hidden) rl._writeToOutput = (str) => { if (str === query) process.stdout.write(str); };
      rl.question(query, (answer) => {
        if (hidden) { rl._writeToOutput = original; process.stdout.write('\n'); }
        resolve(String(answer ?? '').trim() || defaultValue);
      });
    });
  }
  // Non-interactive / piped mode: buffer all lines so every prompt gets one.
  process.stdout.write(query);
  const answer = pipedLines[lineIndex++] ?? '';
  if (!hidden) process.stdout.write(`${answer}\n`);
  else process.stdout.write('\n');
  return Promise.resolve(String(answer).trim() || defaultValue);
}

async function askValid(label, validate, options = {}) {
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const value = await ask(label, options);
    if (validate(value)) return value;
    console.log('  ⚠️  That value looks like a placeholder or is invalid. Please paste the real value.');
  }
  throw new Error(`Could not collect a valid value for ${label}`);
}

function randomHex(bytes = 32) { return crypto.randomBytes(bytes).toString('hex'); }
const optional = (v) => !v || isRealValue(v, 1);

async function main() {
  console.log('\n🔐 VC TOPUP — real account + real diamond credential setup');
  console.log('   Values are written ONLY to .env (git-ignored, mode 0600). Never paste keys into chat.\n');

  if (fs.existsSync(ENV_PATH)) {
    const overwrite = await ask('.env already exists. Overwrite it? [y/N]: ');
    if (!/^y(es)?$/i.test(overwrite)) {
      console.log('Aborted. Your existing .env was not changed.');
      rl?.close();
      return;
    }
  }

  const values = {
    PORT: e.PORT || '4000',
    PAYMENT_MODE: 'live',
    VC_SECRET: randomHex(32),
    CRON_SECRET: randomHex(32),
    DATABASE_URL: await askValid('Hosted Postgres URL (postgres://…?sslmode=require): ', isPostgresUrl, { hidden: true, defaultValue: e.DATABASE_URL || '' }),
    PUBLIC_BASE_URL: await askValid('Public HTTPS origin (https://your-domain.com): ', isHttpsUrl, { defaultValue: e.PUBLIC_BASE_URL || '' }),
    BAKONG_API_TOKEN: await askValid('NBC/Bakong developer token: ', (v) => isRealValue(v, 20), { hidden: true, defaultValue: e.BAKONG_API_TOKEN || '' }),
    BAKONG_ACCOUNT_ID: await askValid('Your Bakong Account ID (name@bank): ', isBakongAccountId, { defaultValue: e.BAKONG_ACCOUNT_ID || '' }),
    BAKONG_MERCHANT_NAME: await askValid('Registered merchant name: ', (v) => isRealValue(v, 2), { defaultValue: e.BAKONG_MERCHANT_NAME || '' }),
    BAKONG_MERCHANT_CITY: await askValid('Merchant city: ', (v) => isRealValue(v, 2), { defaultValue: e.BAKONG_MERCHANT_CITY || '' }),
    BAKONG_CURRENCY: 'USD',
    BAKONG_QR_TTL_MINUTES: '10',
    BAKONG_POLL_THROTTLE_MS: '4000',
    BAKONG_API_BASE: 'https://api-bakong.nbc.gov.kh/v1',
    PARTNER_PROVIDER: 'shop2topup',
    SHOP2TOPUP_BASE_URL: 'https://shop2topup.com/api/endpoints/v1',
    SHOP2TOPUP_API_KEY: await askValid('Shop2Topup API key (<keyId>.<secret>): ', isShop2TopupKey, { hidden: true, defaultValue: e.SHOP2TOPUP_API_KEY || '' }),
    SHOP2TOPUP_WEBHOOK_SECRET: await askValid('Shop2Topup webhook signing secret: ', (v) => isStrongSecret(v, 16), { hidden: true, defaultValue: e.SHOP2TOPUP_WEBHOOK_SECRET || '' }),
    SHOP2TOPUP_CATEGORY_ID: await askValid('Provider category ID for requirements (optional, press Enter): ', optional, { defaultValue: e.SHOP2TOPUP_CATEGORY_ID || '' }),
    SHOP2TOPUP_VALIDATE_PLAYER: 'true',
    SHOP2TOPUP_MAX_COST_RATIO: '1',
    SHOP2TOPUP_TIMEOUT_MS: '15000',
  };

  const lines = [
    '# Generated by npm run setup:live — NEVER commit this file.',
    ...Object.entries(values)
      .filter(([, v]) => v !== '')
      .map(([k, v]) => `${k}=${String(v).includes('#') ? JSON.stringify(v) : v}`),
    '',
    '# Optional: add SHOP2TOPUP_DEFAULT_SERVER, BAKONG_MERCHANT_ID, etc.',
    '# Map real diamond IDs in Admin → Real integrations, or set SHOP2TOPUP_ITEM_MAP.',
    '',
  ];
  fs.writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 });
  fs.chmodSync(ENV_PATH, 0o600);

  // Validate with the same gate the production server uses.
  Object.assign(process.env, values, { PAYMENT_MODE: 'live' });
  const { integrationStatus } = await import('../server/config.js');
  const status = integrationStatus();

  console.log('\n✅ Wrote .env with strong generated VC_SECRET and CRON_SECRET.');
  console.log(`   Provider: ${status.providerLabel}`);
  console.log(`   Webhook:  ${status.webhookUrl}  (${status.webhookSignatureHeader})`);
  console.log(`   Real SKUs mapped: ${status.skuCoverage.mapped}/${status.skuCoverage.total}`);
  if (status.blockers.length) console.log(`   Live gate blockers: ${status.blockers.join(', ')}`);
  else console.log('   Live gate: READY');

  console.log('\n📌 Next steps');
  console.log('   1. Copy EVERY variable in .env into Vercel → Settings → Environment Variables.');
  console.log('   2. Register the webhook URL above in the Shop2Topup panel and use the same webhook secret.');
  console.log('   3. Run `npm run check:live -- --probe` to test the real account and key.');
  console.log('   4. Sign in as admin → Real integrations → load the catalogue → map every package to a real item ID.');
  console.log('   5. Confirm Bakong production allows your server IP; otherwise use an NBC-approved relay.');
  console.log('   6. Test one small real order before opening to customers. Keep PAYMENT_MODE=sandbox until then.\n');
  rl?.close();
}

main().catch((err) => {
  console.error(`\n❌ Setup failed: ${err.message}\n`);
  rl?.close();
  process.exitCode = 1;
});
